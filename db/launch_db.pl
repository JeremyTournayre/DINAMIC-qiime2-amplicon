#
# db/launch_db.pl - orchestrator for QIIME2 classifier building.
# Reads db/input.tsv and calls build_classifier.sh for each primer/database
# combination.
#
# Author: Jeremy Tournayre
#
# Usage:  perl launch_db.pl [input_file]   (defaults to input.tsv)
#
# The QIIME2 environment must be activated (or CONDA_ENV_QIIME2 exported)
# before running this script directly. When submitted via
# launch_db_multipleqsub.pl, CONDA_ENV_QIIME2 arrives already injected via
# `qsub -v` and is used as-is — build_classifier.sh re-activates this same
# environment explicitly for each job anyway.

use strict;
use warnings;

# If CONDA_ENV_QIIME2 is already set in this shell's environment (e.g.
# injected by `qsub -v CONDA_ENV_QIIME2=...` from launch_db_multipleqsub.pl,
# or exported manually before running this script directly), use it as-is —
# do NOT silently re-read config.sh's default, which could disagree with
# what the person actually activated.
my $conda_env_qiime2 = $ENV{'CONDA_ENV_QIIME2'};
if (defined($conda_env_qiime2) && length($conda_env_qiime2)) {
    print "Using QIIME2 environment (from shell environment): $conda_env_qiime2\n";
} else {
    # Fall back to config.sh's default only if nothing was already set.
    $conda_env_qiime2 = `bash -c "source ../config.sh && echo \\\$CONDA_ENV_QIIME2"`;
    chomp($conda_env_qiime2);
    if (!length($conda_env_qiime2)) {
        die "Could not read CONDA_ENV_QIIME2 from config.sh. Check that config.sh exists at the repository root.\n";
    }
    print "Using QIIME2 environment (from config.sh default): $conda_env_qiime2\n";
}
my %targets;

my $file = "input.tsv";
if (defined($ARGV[0])) { $file = $ARGV[0]; }
`dos2unix $file`;

open(F, $file) or die "Cannot open $file: $!";
my $row = <F>;
chomp($row);
my @title = split("\t", $row);

while (<F>) {
    chomp($_);
    my @split  = split("\t", $_);
    my $target = shift(@split);
    my $i      = 1;
    foreach (@split) {
        $targets{$target}{ $title[$i] } = $_;
        $i++;
    }
}
close(F);

foreach (sort keys %targets) {
    my $target = $_;
    my $dir    = "Data/" . $targets{$target}{'Database'} . "/" . $conda_env_qiime2 . "/" . $target;
    # Created here (not left to build_classifier.sh) because run.conf must be
    # written into this directory before build_classifier.sh is even called.
    `mkdir -p $dir` unless -d $dir;

    # Dedicated subdirectories for per-job run.conf and log files, mirroring
    # launch.pl's convention. Required because launch_db_multipleqsub.pl can
    # dispatch input.tsv rows as separate concurrent qsub jobs: if two rows
    # ever shared the same DB_TARGET name (e.g. by mistake), a run.conf path
    # derived only from $dir would be the SAME file for both jobs, letting
    # one job's write race with another job's read.
    my $logs_dir     = "$dir/logs";
    my $run_conf_dir = "$dir/run_conf";
    `mkdir -p $logs_dir`     unless -d $logs_dir;
    `mkdir -p $run_conf_dir` unless -d $run_conf_dir;

    # Job identifier: SGE job number (sortable by submission order/date)
    # as prefix, then the DB_TARGET name (human-readable), then a
    # PID+random suffix to guarantee uniqueness under concurrent execution.
    # $ENV{JOB_ID} is set by SGE for qsub-submitted jobs; falls back to the
    # process PID when run directly (no qsub).
    my $sge_job_id = defined($ENV{'JOB_ID'}) ? $ENV{'JOB_ID'} : $$;
    my $job_id = $sge_job_id . '_' . $target . '_'
               . join('', map { chr(65 + int(rand(26))) } 1..6);
    $job_id =~ s/[^-\w.]/_/g;    # sanitize for use in a filename

    my $out      = "$logs_dir/$job_id.log";
    my $run_conf = "$run_conf_dir/$job_id.conf";

    open(my $cfh, '>', $run_conf) or die "Cannot write $run_conf: $!";
    print $cfh "# Auto-generated by launch_db.pl on " . localtime() . "\n";
    print $cfh "DB_TARGET='"   . $target                           . "'\n";
    print $cfh "PRIMER_F='"    . $targets{$target}{'primer_F'}    . "'\n";
    print $cfh "PRIMER_R='"    . $targets{$target}{'primer_R'}    . "'\n";
    print $cfh "DATABASE='"    . $targets{$target}{'Database'}    . "'\n";
    print $cfh "MIN_LENGTH='"  . $targets{$target}{'Min-length'}  . "'\n";
    print $cfh "MAX_LENGTH='"  . $targets{$target}{'Max-length'}  . "'\n";
    close($cfh);

    system("bash build_classifier.sh '$run_conf' 1>>$out 2>&1");

    # Clean up the per-job run.conf once build_classifier.sh has finished
    # with it — it has already been sourced by then, and PROVENANCE.txt /
    # the log file keep a record of what ran.
    unlink($run_conf);
}